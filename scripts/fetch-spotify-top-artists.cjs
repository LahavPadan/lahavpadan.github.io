/**
 * Refreshes _data/spotify.yml with the top artists Spotify reports for the
 * account whose refresh token sits in SPOTIFY_REFRESH_TOKEN.
 *
 * Runs as a step in the Pages workflow before `jekyll build`; the refresh
 * token stays a GitHub Secret and only the compiled artist list — public
 * information already visible on any Spotify profile — enters the artifact.
 *
 * Deploy safety: any failure exits 0 without touching the data file, so a
 * Spotify outage or a rotated token can never break a release. The build
 * still runs, and whoami.md falls back to the hand-maintained list in
 * _data/whoami.yml until the next successful refresh.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const OUTPUT_PATH = path.join(__dirname, '..', '_data', 'spotify.yml');
const TIME_RANGE = 'short_term';   // ~last 4 weeks; long_term for all-time
const LIMIT = 5;

async function refreshAccessToken(clientId, clientSecret, refreshToken) {
  const basic = Buffer.from(`${clientId}:${clientSecret}`).toString('base64');
  const res = await fetch('https://accounts.spotify.com/api/token', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/x-www-form-urlencoded',
      'Authorization': `Basic ${basic}`,
    },
    body: new URLSearchParams({
      grant_type: 'refresh_token',
      refresh_token: refreshToken,
    }).toString(),
  });
  if (!res.ok) throw new Error(`token exchange failed: ${res.status} ${await res.text()}`);
  const { access_token } = await res.json();
  if (!access_token) throw new Error('token response missing access_token');
  return access_token;
}

async function fetchTopArtists(accessToken) {
  const url = `https://api.spotify.com/v1/me/top/artists?time_range=${TIME_RANGE}&limit=${LIMIT}`;
  const res = await fetch(url, { headers: { Authorization: `Bearer ${accessToken}` } });
  if (!res.ok) throw new Error(`top-artists failed: ${res.status} ${await res.text()}`);
  const data = await res.json();
  return Array.isArray(data.items) ? data.items : [];
}

// Pick the smallest image at or above 160px, so the 52px cover in the widget
// rasterises cleanly on retina without pulling a 640px file per artist.
function pickImage(images) {
  if (!images || !images.length) return null;
  const sorted = images.slice().sort((a, b) => (a.height || 0) - (b.height || 0));
  return (sorted.find((img) => (img.height || 0) >= 160) || sorted[sorted.length - 1]).url;
}

const HEBREW_RANGE = /[\u0590-\u05FF]/;

function yamlEscape(value) {
  return String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

function toYaml(artists) {
  const header =
    '# Auto-generated by scripts/fetch-spotify-top-artists.cjs at build time.\n' +
    '# Regenerated on every deploy; do not edit by hand — changes are overwritten.\n' +
    '\n' +
    'spotify_top_artists:\n';

  const body = artists.map((a) => {
    const image = pickImage(a.images);
    const rtl = HEBREW_RANGE.test(a.name);
    const lines = [
      `  - name: "${yamlEscape(a.name)}"`,
      `    url: "${a.external_urls && a.external_urls.spotify || ''}"`,
      `    image: "${image || ''}"`,
    ];
    if (rtl) { lines.push('    lang: "he"', '    dir: "rtl"'); }
    return lines.join('\n');
  }).join('\n');

  return `${header}${body}\n`;
}

async function main() {
  const { SPOTIFY_CLIENT_ID, SPOTIFY_CLIENT_SECRET, SPOTIFY_REFRESH_TOKEN } = process.env;

  if (!SPOTIFY_CLIENT_ID || !SPOTIFY_CLIENT_SECRET || !SPOTIFY_REFRESH_TOKEN) {
    // Deploys from forks or local runs without secrets are expected — do not
    // fail; whoami.md will use the hand-maintained fallback list.
    console.warn('[spotify] secrets not configured; skipping fetch');
    return;
  }

  const accessToken = await refreshAccessToken(
    SPOTIFY_CLIENT_ID, SPOTIFY_CLIENT_SECRET, SPOTIFY_REFRESH_TOKEN
  );
  const artists = await fetchTopArtists(accessToken);
  if (!artists.length) {
    console.warn('[spotify] top-artists returned empty; leaving data file untouched');
    return;
  }

  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  fs.writeFileSync(OUTPUT_PATH, toYaml(artists), 'utf8');
  console.log(`[spotify] wrote ${artists.length} artists to ${OUTPUT_PATH}`);
}

main().catch((err) => {
  console.warn('[spotify] fetch failed, keeping previous data:', err.message);
  process.exitCode = 0;
});
